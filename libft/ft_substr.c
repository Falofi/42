#include "libft.h"
#include <stdlib.h>

static char	*ft_strndup(const char *s, size_t len)
{
	char	*res;
	size_t	i;

	res = malloc(len + 1);
	if (!res)
		return (NULL);
	i = 0;
	while (i < len)
	{
		res[i] = s[i];
		i++;
	}
	res[i] = '\0';
	return (res);
}

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	size_t	s_len;

	if (!s)
		return (NULL);
	s_len = ft_strlen(s);
	if (start >= s_len)
		return (ft_strndup("", 0));
	if (len > s_len - start)
		len = s_len - start;
	return (ft_strndup(s + start, len));
}
